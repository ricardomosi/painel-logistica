-- Schema completo do Logística JPatrício (logistica-v2 / sa-east-1)
CREATE EXTENSION IF NOT EXISTS pgcrypto;
CREATE EXTENSION IF NOT EXISTS pg_trgm;

CREATE TABLE IF NOT EXISTS public.motoristas (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  nome text NOT NULL,
  telefone text,
  cnh text,
  ativo boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.veiculos (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  placa text NOT NULL,
  modelo text,
  motorista_padrao_id uuid REFERENCES public.motoristas(id) ON DELETE SET NULL,
  ativo boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.vendedores (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  nome text NOT NULL,
  unidade text DEFAULT 'Matriz',
  nome_completo text,
  ativo boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.profiles (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  nome text,
  email text UNIQUE,
  role text NOT NULL DEFAULT 'motorista',
  motorista_id uuid REFERENCES public.motoristas(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  senha text DEFAULT '123456'
);

CREATE TABLE IF NOT EXISTS public.materiais (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  codigo text,
  nome text NOT NULL,
  unidade text DEFAULT 'UN',
  peso_padrao_kg numeric DEFAULT 0,
  valor_padrao numeric DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  preco_buscar numeric DEFAULT 0,
  preco_trazer numeric DEFAULT 0,
  categoria text,
  ncm text,
  filial text,
  sub text,
  sagi_id text,
  ativo boolean NOT NULL DEFAULT true
);

CREATE INDEX IF NOT EXISTS idx_materiais_nome_trgm ON public.materiais USING gin (nome gin_trgm_ops);
CREATE INDEX IF NOT EXISTS idx_materiais_codigo_trgm ON public.materiais USING gin (codigo gin_trgm_ops);
CREATE INDEX IF NOT EXISTS idx_materiais_ativo ON public.materiais (ativo);

CREATE TABLE IF NOT EXISTS public.coletas (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  data_registro date NOT NULL DEFAULT CURRENT_DATE,
  hora_registro time DEFAULT CURRENT_TIME,
  fornecedor text NOT NULL,
  responsavel text,
  tipo text DEFAULT 'Envio',
  placa text,
  veiculo_id uuid REFERENCES public.veiculos(id) ON DELETE SET NULL,
  motorista_id uuid REFERENCES public.motoristas(id) ON DELETE SET NULL,
  telefone text,
  status text NOT NULL DEFAULT 'pendente',
  data_conclusao date,
  hora_conclusao time,
  coluna_kanban text DEFAULT 'atualizacoes',
  board_type text DEFAULT 'coleta',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz DEFAULT now(),
  endereco text,
  urgente boolean NOT NULL DEFAULT false
);

CREATE TABLE IF NOT EXISTS public.entregas (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  data_registro date NOT NULL DEFAULT CURRENT_DATE,
  hora_registro time DEFAULT CURRENT_TIME,
  cliente text NOT NULL,
  endereco text,
  placa text,
  veiculo_id uuid REFERENCES public.veiculos(id) ON DELETE SET NULL,
  motorista_id uuid REFERENCES public.motoristas(id) ON DELETE SET NULL,
  boleto text,
  vendedor text,
  local_carregamento text DEFAULT 'MATRIZ',
  cadastrador_entrega text,
  status text NOT NULL DEFAULT 'pendente',
  frete numeric DEFAULT 0,
  valor_entrega numeric DEFAULT 0,
  telefone text,
  data_inicio date,
  hora_inicio time,
  km_inicial numeric DEFAULT 0,
  km_final numeric DEFAULT 0,
  km_total numeric GENERATED ALWAYS AS (GREATEST(COALESCE(km_final, 0) - COALESCE(km_inicial, 0), 0)) STORED,
  data_conclusao date,
  hora_conclusao time,
  como_foi_entrega text,
  coluna text DEFAULT 'atualizacoes',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz DEFAULT now(),
  urgente boolean NOT NULL DEFAULT false
);

CREATE TABLE IF NOT EXISTS public.romaneios (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  entrega_id bigint REFERENCES public.entregas(id) ON DELETE CASCADE,
  numero_romaneio integer GENERATED BY DEFAULT AS IDENTITY,
  observacoes text DEFAULT '',
  peso_total_kg numeric DEFAULT 0,
  valor_total numeric DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.romaneio_itens (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  romaneio_id uuid REFERENCES public.romaneios(id) ON DELETE CASCADE,
  material_id uuid REFERENCES public.materiais(id) ON DELETE SET NULL,
  codigo_material text,
  nome_material text,
  quantidade numeric DEFAULT 1,
  peso_unitario_kg numeric DEFAULT 0,
  peso_total_kg numeric DEFAULT 0,
  valor_unitario numeric DEFAULT 0,
  valor_total numeric DEFAULT 0,
  unidade text DEFAULT 'UN'
);

-- RLS e políticas abertas (compatível com o cliente atual do Logística)
DO $$
DECLARE
  t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['motoristas','veiculos','vendedores','profiles','materiais','coletas','entregas','romaneios','romaneio_itens']
  LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY;', t);
    EXECUTE format('DROP POLICY IF EXISTS "Allow all access" ON public.%I;', t);
    EXECUTE format('CREATE POLICY "Allow all access" ON public.%I FOR ALL USING (true) WITH CHECK (true);', t);
  END LOOP;
END $$;

-- Publicação Realtime para todas as 9 tabelas monitoradas pelo useSupabaseRealtime
DO $$
DECLARE
  t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['motoristas','veiculos','vendedores','profiles','materiais','coletas','entregas','romaneios','romaneio_itens']
  LOOP
    IF NOT EXISTS (
      SELECT 1 FROM pg_publication_tables
      WHERE pubname = 'supabase_realtime' AND schemaname = 'public' AND tablename = t
    ) THEN
      EXECUTE format('ALTER PUBLICATION supabase_realtime ADD TABLE public.%I;', t);
    END IF;
  END LOOP;
END $$;

